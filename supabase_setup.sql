-- SPARK content management schema for Supabase.
-- Run this in Supabase SQL Editor. Do not put the service_role key in website code.

create table if not exists public.user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('admin','student')) default 'student',
  created_at timestamptz not null default now()
);

create or replace function public.is_spark_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.user_roles where user_id = auth.uid() and role = 'admin'); $$;
revoke all on function public.is_spark_admin() from public;
grant execute on function public.is_spark_admin() to authenticated;

create table if not exists public.members (
 id bigint generated by default as identity primary key,
 title text not null,
 role text,
 description text,
 image_url text,
 created_at timestamptz not null default now()
);
create table if not exists public.games (
 id bigint generated by default as identity primary key,
 title text not null,
 category text,
 description text,
 image_url text,
 created_at timestamptz not null default now()
);
create table if not exists public.announcements (
 id bigint generated by default as identity primary key,
 title text not null,
 category text,
 body text,
 image_url text,
 created_at timestamptz not null default now()
);
-- study_resources already exists in the initial setup; add columns safely if needed.
alter table public.study_resources add column if not exists created_at timestamptz not null default now();
alter table public.study_resources add column if not exists title text;
alter table public.study_resources add column if not exists subject text;
alter table public.study_resources add column if not exists description text;
alter table public.study_resources add column if not exists file_path text;
alter table public.study_resources add column if not exists file_type text;

alter table public.user_roles enable row level security;
create policy "Users can read own role" on public.user_roles for select to authenticated using (user_id = auth.uid() or public.is_spark_admin());
create policy "Admins manage roles" on public.user_roles for all to authenticated using (public.is_spark_admin()) with check (public.is_spark_admin());

-- Content is publicly readable; only verified admins can add/edit/delete.
DO $$ DECLARE t text; BEGIN
 FOREACH t IN ARRAY ARRAY['members','games','announcements','study_resources'] LOOP
  EXECUTE format('alter table public.%I enable row level security', t);
  EXECUTE format('drop policy if exists "Public can read %1$s" on public.%1$I', t);
  EXECUTE format('create policy "Public can read %1$s" on public.%1$I for select to anon, authenticated using (true)', t);
  EXECUTE format('drop policy if exists "Admins manage %1$s" on public.%1$I', t);
  EXECUTE format('create policy "Admins manage %1$s" on public.%1$I for all to authenticated using (public.is_spark_admin()) with check (public.is_spark_admin())', t);
 END LOOP;
END $$;
GRANT SELECT ON public.members, public.games, public.announcements, public.study_resources TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.members, public.games, public.announcements, public.study_resources TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;

-- Storage policies for private bucket study-files. Admins upload/update/delete; authenticated users can download.
DROP POLICY IF EXISTS "Authenticated users can download study files hdyi5v_0" ON storage.objects;
DROP POLICY IF EXISTS "Authenticated users can download SPARK study files" ON storage.objects;
CREATE POLICY "Authenticated users can download SPARK study files" ON storage.objects FOR SELECT TO authenticated USING (bucket_id = 'study-files');
DROP POLICY IF EXISTS "SPARK admins upload study files" ON storage.objects;
CREATE POLICY "SPARK admins upload study files" ON storage.objects FOR INSERT TO authenticated WITH CHECK (bucket_id = 'study-files' AND public.is_spark_admin());
DROP POLICY IF EXISTS "SPARK admins update study files" ON storage.objects;
CREATE POLICY "SPARK admins update study files" ON storage.objects FOR UPDATE TO authenticated USING (bucket_id = 'study-files' AND public.is_spark_admin()) WITH CHECK (bucket_id = 'study-files' AND public.is_spark_admin());
DROP POLICY IF EXISTS "SPARK admins delete study files" ON storage.objects;
CREATE POLICY "SPARK admins delete study files" ON storage.objects FOR DELETE TO authenticated USING (bucket_id = 'study-files' AND public.is_spark_admin());
